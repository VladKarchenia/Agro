import type { Company } from '~/data/company'
import type { LegalSection } from './privacy-policy'

export const CONSENT_TITLE = 'Согласие на обработку персональных данных'

// Версия текста согласия сохраняется вместе с заявкой: доказывать получение согласия обязан оператор
// (ст. 5 Закона 99-З). Меняйте при любой правке текста ниже и политики.
export const CONSENT_VERSION = '2026-10-draft-2'

// Информация, которую нужно предоставить до получения согласия (ст. 5, п. 5 Закона 99-З).
// Права разъясняются отдельным разделом, «отдельно от иной предоставляемой информации».
// Текст требует проверки юристом (см. docs/specs/legal-privacy.md).
export function buildConsentDocument(company: Company): LegalSection[] {
  const field = (value: string | null, label: string) => value ?? `[${label}]`

  const operator = field(company.legalName, 'наименование организации')
  const unp = field(company.unp, 'УНП')
  const address = field(company.address, 'место нахождения')
  const email = field(company.email, 'адрес электронной почты')
  const hosting = field(company.hostingProvider, 'наименование хостинг-провайдера')
  const retention = field(company.retentionPeriod, 'срок хранения')

  return [
    {
      id: 'operator',
      title: 'Оператор',
      blocks: [
        {
          type: 'p',
          text: `${operator}, УНП ${unp}, место нахождения: ${address}. Контакты для обращений: ${email}.`,
        },
      ],
    },
    {
      id: 'purposes',
      title: 'Цели обработки',
      blocks: [
        {
          type: 'p',
          text: 'Приём и обработка заявки, связь с вами, подготовка и согласование предложения, заключение и исполнение договора.',
        },
      ],
    },
    {
      id: 'data',
      title: 'Какие данные обрабатываются',
      blocks: [
        {
          type: 'p',
          text: 'Имя, телефон, email, наименование организации и УНП (для организаций), город или адрес доставки, комментарий, состав заявки.',
        },
      ],
    },
    {
      id: 'actions',
      title: 'Действия с данными и способы обработки',
      blocks: [
        {
          type: 'p',
          text: 'Сбор, запись, хранение, использование, удаление. Обработка осуществляется с использованием средств автоматизации.',
        },
      ],
    },
    {
      id: 'processors',
      title: 'Уполномоченные лица',
      blocks: [
        {
          type: 'p',
          text: `Хостинг-провайдер, обеспечивающий работу сайта и хранение данных: ${hosting}. Он действует по поручению оператора.`,
        },
      ],
    },
    {
      id: 'term',
      title: 'Срок согласия',
      blocks: [
        {
          type: 'p',
          text: `${retention}. Согласие можно отозвать в любое время.`,
        },
      ],
    },
    {
      id: 'rights',
      title: 'Ваши права и последствия согласия',
      blocks: [
        { type: 'p', text: 'Вы вправе:' },
        {
          type: 'ul',
          items: [
            'в любое время без объяснения причин отозвать согласие: в течение 15 дней мы прекратим обработку и удалим данные, если нет иных оснований для их обработки;',
            'получить информацию об обработке ваших данных (ответ в течение 5 рабочих дней);',
            'требовать прекращения обработки и удаления данных, если для обработки нет оснований;',
            'обжаловать наши действия в Национальный центр защиты персональных данных, а его решение в суде.',
          ],
        },
        {
          type: 'p',
          text: `Чтобы отозвать согласие или воспользоваться правами, направьте заявление на ${email} или по адресу ${address}. Порядок подачи заявления описан в политике обработки персональных данных.`,
        },
        {
          type: 'p',
          text: 'Если вы дадите согласие, мы сможем принять и обработать заявку через сайт. Если откажетесь, заявку через сайт отправить не получится, но вы можете связаться с нами по контактам на странице «Контакты».',
        },
      ],
    },
  ]
}
