import type { Company } from '~/data/company'

// Версия текста согласия сохраняется вместе с заявкой: доказывать получение согласия обязан оператор
// (ст. 5 Закона 99-З). Меняйте при любой правке текста ниже и политики.
export const CONSENT_VERSION = '2026-10-draft-1'

export interface ConsentInfo {
  rows: { label: string; value: string }[]
  rights: string
}

// Информация, которую нужно показать до согласия (ст. 5, п. 5), текст требует проверки юристом
export function buildConsentInfo(company: Company): ConsentInfo {
  const field = (value: string | null, label: string) => value ?? `[${label}]`

  return {
    rows: [
      {
        label: 'Оператор',
        value: `${field(company.legalName, 'наименование организации')}, УНП ${field(company.unp, 'УНП')}, ${field(company.address, 'место нахождения')}`,
      },
      {
        label: 'Цели',
        value:
          'приём и обработка заявки, связь с вами, подготовка предложения, заключение и исполнение договора',
      },
      {
        label: 'Данные',
        value:
          'имя, телефон, email, наименование организации и УНП (для организаций), город или адрес доставки, комментарий, состав заявки',
      },
      {
        label: 'Действия',
        value:
          'сбор, запись, хранение, использование, удаление; обработка с использованием средств автоматизации',
      },
      {
        label: 'Уполномоченные лица',
        value: `хостинг-провайдер ${field(company.hostingProvider, 'наименование хостинг-провайдера')}`,
      },
      { label: 'Срок', value: field(company.retentionPeriod, 'срок хранения') },
    ],
    rights:
      'Вы вправе в любое время отозвать согласие (в течение 15 дней мы прекратим обработку и удалим данные), получить информацию об обработке своих данных, требовать их удаления и обжаловать наши действия в Национальный центр защиты персональных данных. Если вы не дадите согласие, мы не сможем принять заявку через сайт, но вы можете связаться с нами по контактам на странице «Контакты».',
  }
}
