interface Input {
  cores: 2 | 4 | 5
  section: number
  /** Обозначение конструкции жилы и нулевой/защитной жил, как в названии: «ок (N)», «ок (N, PE)», «ож» */
  marking: string
  /** Состав жил простыми словами */
  layout: string
  /** Наружный диаметр, мм. Указываем, только если он есть в источнике */
  outerDiameter?: number
  manufacturer: Manufacturer
  /** Окончание адреса товара, чтобы различать исполнения с одинаковым сечением */
  slugSuffix: string
  sourceUrl: string
}

function avbbshv(input: Input): Product {
  const { cores, section, marking, layout, outerDiameter, manufacturer } = input
  const size = sizeLabel(cores, section)
  const name = `Кабель АВБбШв ${size} ${marking} - 1 кВ`

  const description = [
    `${name} — силовой бронированный кабель с алюминиевыми жилами: ${coresPhrase(cores, ['однопроволочная', 'однопроволочные', 'однопроволочных'])} сечением ${section} мм², изоляция и защитный шланг из ПВХ-пластиката, броня из стальных оцинкованных лент. Номинальное напряжение — 1 кВ, частота 50 Гц.`,
    `Конструкция из ${coresGenitive(cores)}: ${layout}. Кабель выпускает ${manufacturer.legalName}, страна происхождения — Беларусь, гарантийный срок — 5 лет.`,
  ]
  if (outerDiameter) {
    description.push(
      `Наружный диаметр кабеля — ${outerDiameter} мм. Его учитывают при выборе кабельных вводов, труб и креплений.`,
    )
  }

  return {
    slug: `kabel-avbbshv-${size.replace('х', 'x')}-${input.slugSuffix}`,
    categorySlug: subcategory.categorySlug,
    subcategorySlug: subcategory.slug,
    name,
    summary: `Силовой бронированный, алюминиевые жилы ${size} мм², 1 кВ, изоляция ПВХ.`,
    description,
    specs: cableSpecs({
      series: 'АВБбШв',
      manufacturer,
      cores,
      section: String(section),
      voltage: '1 кВ',
      material: 'Алюминий',
      conductorClass: '1, однопроволочная',
      shape: 'Круглый',
      insulation: PVC,
      sheath: PVC,
      color: { name: 'Цвет оболочки', value: 'Чёрный' },
      armoured: 'Да, стальные оцинкованные ленты',
      noFlame: false,
      lowSmoke: false,
      outerDiameter: outerDiameter ? `${outerDiameter} мм` : undefined,
      guarantee: '5 лет',
    }),
    brand: manufacturer.brand,
    price: null,
    sourceUrl: input.sourceUrl,
  }
}

